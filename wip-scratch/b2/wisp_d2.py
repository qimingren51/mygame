import math
INK=(40,36,32); MID=(85,80,74); PALE=(130,128,124)
C = (5.0, 13.4)
def spiral_pts(th0=math.pi*0.55, th1=math.pi*2.5, r0=0.45, r1=3.05, n=40):
    out=[]
    for i in range(n):
        th = th0 + (th1-th0)*i/(n-1)
        r = r0 + (r1-r0)*((th-th0)/(th1-th0))**0.9
        out.append((C[0]+r*math.cos(th), C[1]+r*math.sin(th)))
    return out
