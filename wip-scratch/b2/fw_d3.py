import math
DEEP=(37,85,94); TEAL=(63,140,136); MINT=(124,203,190); PALE=(189,238,226); WHITE=(242,255,252)
TAIL = [(2.0, 14.0), (-2.5, 13.2), (-7.5, 13.0), (-12.0, 13.8), (-15.6, 15.6), (-18.0, 18.6), (-18.6, 21.4)]
SHAPES = []
# 往上窜的火舌（火往上走）：沿尾巴上沿，一簇簇往后上方
for (x, y, ln, w, col) in [(-1.0, 15.6, 4.4, 1.6, TEAL), (-5.0, 16.4, 5.4, 1.8, TEAL), (-9.4, 16.8, 5.6, 1.8, DEEP),
                           (-13.2, 18.0, 4.8, 1.5, DEEP), (-16.4, 20.6, 3.6, 1.2, DEEP)]:
    pts = [(x, y), (x - ln * 0.35, y + ln * 0.55), (x - ln * 0.85, y + ln * 0.95)]
    SHAPES.append(('stroke', (pts, [w, w * 0.55, 0.0]), col))
SHAPES += [
  ('stroke', (TAIL, [3.4, 6.4, 8.0, 8.2, 7.0, 4.6, 0.6]), DEEP),
  ('stroke', ([(p[0]+0.2, p[1]+0.4) for p in TAIL[:-1]], [2.6, 4.8, 6.0, 6.0, 4.6, 1.2]), TEAL),
  ('stroke', ([(p[0]+0.5, p[1]+0.7) for p in TAIL[:-2]], [1.8, 3.0, 3.8, 3.4, 1.0]), MINT),
]
# 头：前头尖的一团火（吻）
def egg(cx, cy, rx, ry, k, n=60):
    out = []
    for t in [2*math.pi*i/n for i in range(n)]:
        x, y = math.cos(t), math.sin(t)
        sx = rx * (1.0 + k * x)  # 前半拉长、后半收短
        out.append((cx + sx * x, cy + ry * y * (1 - 0.35 * max(0, x) ** 2)))
    return out
SHAPES += [
  ('poly', egg(5.0, 14.2, 4.0, 3.5, 0.28), TEAL),
  ('poly', egg(5.3, 14.4, 3.3, 2.8, 0.25), MINT),
  ('poly', egg(5.7, 14.6, 2.2, 1.9, 0.2), PALE),
  # 耳：两簇高高往后上方窜的火舌
  ('poly', [(2.2, 16.4), (0.4, 23.0), (4.6, 17.4)], MINT),
  ('poly', [(4.4, 17.0), (3.4, 22.0), (6.6, 17.0)], TEAL),
  # 眼（细长、往后上挑）
  ('poly', [(5.4, 15.8), (7.4, 15.0), (7.9, 15.2), (7.0, 15.9)], DEEP),
  ('poly', [(8.6, 14.9), (9.6, 14.6), (9.5, 15.1)], DEEP),
]
